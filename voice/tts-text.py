#!/usr/bin/env python
"""Текст для синтеза: из текста на экране — в текст для голоса.

Зачем отдельный слой: то, что читает ребёнок, и то, что произносит
нейросеть, — разные вещи. На экране «33 буквы», «ъ и ь», «твёрдый знак
после согласной» — коротко и понятно. В озвучке те же места должны
звучать как речь: «тридцать три буквы», «твёрдый знак и мягкий знак»,
пауза там, где глаз спотыкается о запятую.

Что делает модуль:
  * ставит ударения из voice/stress-ru.txt — словаря, где размечено каждое
    многосложное слово из текстов. Размечается всё, что длиннее двух букв:
    буквам и служебным словам знак не нужен, а над буквой он ломает
    произношение («И́я» читалось как две отдельные буквы). Слова,
    размеченные вручную (омограф «мука»), словарь не переписывает;
  * числа превращает в слова: «33» -> «тридцать три»;
  * буквы-знаки разворачивает в названия: «ъ и ь» -> «твёрдый знак и мягкий
    знак»;
  * убирает цепочки одиночных букв: голос читает «б-б-б» по именам («бэ-бэ-бэ»)
    и «й» — как «и краткая», хотя на экране показан звук;
  * переписывает constructions, которые нельзя произнести («дуб-а»,
    «здрав-ый») в слова, которые можно;
  * ставит паузы в местах, где без них голос сливает фразы в одну.

Экранный текст при этом не меняется: ударения и развёрнутые знаки
существуют только здесь, в озвучке.

Запуск: python voice/tts-text.py            # показать примеры
"""
from __future__ import annotations

import re
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DICT_PATH = ROOT / "voice" / "stress-ru.txt"

ACUTE = "́"
# Знак ударения — часть слова, а не мусор между буквами. Без него в
# шаблоне разметка рассыпалась на части: «Мука́» разбирался как «Мука»
# плюс висящий отдельно знак, и в озвучку уходило «Мука́́» — с двумя
# знаками подряд, что нейросеть читает как слово с инородным ударением.
WORD = re.compile("[А-Яа-яЁё{}]+".format(ACUTE))

# Две буквы и короче — это служебные слова и одиночные буквы. Знак ударения
# над ними не нужен, а над буквой он ломает произношение: «И́я» из
# словаря читалось как две отдельные буквы.
MIN_MARKED_LEN = 3

ONES = [
    "", "один", "два", "три", "четыре", "пять", "шесть", "семь", "восемь", "девять",
]
TEENS = [
    "десять", "одиннадцать", "двенадцать", "тринадцать", "четырнадцать",
    "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать", "девятнадцать",
]
TENS = [
    "", "", "двадцать", "тридцать", "сорок", "пятьдесят", "шестьдесят",
    "семьдесят", "восемьдесят", "девяносто",
]
HUNDREDS = [
    "", "сто", "двести", "триста", "четыреста", "пятьсот", "шестьсот",
    "семьсот", "восемьсот", "девятьсот",
]

# Буквы, которые читаются не как буквы. Их названия нужны словами.
# Название всегда с маленькой: регистр на звучание не влияет, а «и Мя́гкий
# знак» в середине фразы звучит как опечатка.
SYMBOL_NAMES = {
    "ъ": "твёрдый знак",
    "ь": "мягкий знак",
    "Ъ": "твёрдый знак",
    "Ь": "мягкий знак",
}

# Паузы перед словами-связками: без запятой фразы слипаются в одну.
PAUSE_BEFORE = (
    "потому что", "а значит", "то есть", "а если", "а когда", "но если",
    "и если", "и когда", "и потому", "и это", "а он", "а она", "а они",
    "и тогда", "и вот", "какой? ", "что делает? ", "где? ",
)

# Длинный перечисляющий ряд читается на одном дыхании и теряет конец.
# Ставим запятую перед «и», если до него тянется список из трёх и более
# коротких членов подряд.
ENUM_TAIL = re.compile(r"(, [^,]{2,18}), и ")

# Цепочка из трёх и более одиночных букв через дефис: «а-а-а», «б-б-б»,
# «м-а-м-а», «й-й-й». Это запись звуков, и голос читает её по именам букв:
# «б-б-б» превращается в «бэ-бэ-бэ», а «й» — в «и краткая». На экране
# буквы нужны, в озвучке — нет: ребёнок читает их сам.
LETTER_CHAIN = re.compile(
    r"(?<![\w-])[а-яё](?:\s*[-–—]\s*[а-яё]){2,}(?![\w-])",
    re.IGNORECASE,
)

# Написания, которые показывают ребёнку, но невозможно произнести: «дуб-а»,
# «здрав-ый», «под-твёрдый знак-езд». В озвучке заменяем словами.
SPOKEN_FIXES: tuple[tuple[str, str], ...] = (
    (
        "Проверь гласным: дуб — дуб-а, снова слышно б.",
        "Проверь гласным: в слове «дуба́» снова слышно «б».",
    ),
    (
        "Проверяй родственным словом: здрав-ый — тут з слышится.",
        "Проверяй родственным словом: в слове «здра́вый» тут «з» слышится.",
    ),
    (
        "Твёрдый знак разделяет приставку и корень: под-ъ-езд, объ-явление, "
        "съел.",
        "Твёрдый знак разделяет приставку и корень: «подъезд», «объявление», "
        "«съел».",
    ),
    # Одиночная «й» в озвучке читается как «и краткая» — это название буквы,
    # а не её звук: проверено, «й» и «и краткая» дают одинаковую
    # длительность. Единственный способ услышать сам звук — назвать слово, в
    # котором он есть. В примере он звучит в слове «май».
    (
        "«Й» — согласная: й-й-й упирается в язык и не тянется.",
        "Этот звук — как в слове «май», в самом конце: он упирается в язык и "
        "не тянется.",
    ),
    # На экране различение сделано capitals: «МУка» и «муКА». В озвучке знаки
    # ударения ставятся вручную, иначе оба слова звучали бы одинаково, а
    # весь смысл примера — в том, что ударение здесь разное.
    (
        "МУка — то, чем посыпают пирог, а муКА — когда трудно.",
        "Мука́ — то, чем посыпа́ют пиро́г, а му́ка — когда́ тру́дно.",
    ),
    # «кроме ъ и ь» после разворачивания знаков звучит как «кроме твёрдый
    # знак и мягкий знак» — грамматически не сходится.
    (
        "Все остальные, кроме твёрдый знак и мягкий знак, — согласные.",
        "Все остальные, кроме твёрдого и мягкого знаков, — согласные.",
    ),
)


def number_to_words(value: int) -> str:
    if value < 0:
        return "минус " + number_to_words(-value)
    if value < 20:
        return (TEENS if value >= 10 else ONES)[value - 10] if value >= 10 else ONES[value]
    if value < 100:
        tens, rest = divmod(value, 10)
        return TENS[tens] + (" " + ONES[rest] if rest else "")
    if value < 1000:
        hundreds, rest = divmod(value, 100)
        return HUNDREDS[hundreds] + (" " + number_to_words(rest) if rest else "")
    return str(value)


def load_stress(path: Path | None = None) -> dict[str, str]:
    """Слово в нижнем регистре -> слово с ударением."""
    source = path if path is not None else DICT_PATH
    if not source.exists():
        return {}
    table: dict[str, str] = {}
    for line in source.read_text(encoding="utf-8").splitlines():
        word = line.strip()
        if not word or word.startswith("#"):
            continue
        plain = unicodedata.normalize("NFC", word.replace(ACUTE, "")).lower()
        table[plain] = word
    return table


def apply_stress(text: str, table: dict[str, str]) -> str:
    def replace(match: re.Match) -> str:
        word = match.group(0)
        if len(word) < MIN_MARKED_LEN:
            # Буквы и служебные слова: знак над ними не нужен, а над буквой
            # он ломает произношение — «И́я» читалось как две буквы.
            return word
        if ACUTE in word:
            # Слово уже размечено вручную: в примере про омографы «Мука́» и
            # «му́ка» различаются только знаком, и словарь переписал бы оба
            # одинаково. Ручная разметка важнее словарной.
            return word
        marked = table.get(word.lower())
        if marked is None:
            return word
        # Регистр берём из исходного слова: иначе «Ударение» в начале
        # фразы превращалось в «ударе́ние», и голос звучал странно.
        if word[:1].isupper():
            return marked[:1].upper() + marked[1:]
        return marked

    return WORD.sub(replace, text)


def spell_numbers(text: str) -> str:
    def replace(match: re.Match) -> str:
        raw = match.group(0)
        # Дробные и годы не трогаем: «3,5» и «2024» — не то и не это.
        if "," in raw or "." in raw or len(raw) > 3:
            return raw
        return number_to_words(int(raw))

    return re.sub(r"\d+", replace, text)


def spell_symbols(text: str) -> str:
    """«ъ и ь» -> «твёрдый знак и мягкий знак», но «подъезд» не трогаем."""
    out = text
    for symbol, name in SYMBOL_NAMES.items():
        # Только когда знак стоит отдельным словом: после буквы это часть слова.
        # Дефис тоже считаем частью слова: в «под-ъ-езд» знак показывают, а не
        # называют — иначе фраза звучала бы «под-твёрдый знак-езд».
        out = re.sub(rf"(?<![\w-]){re.escape(symbol)}(?![\w-])", name, out)
    return out


QUOTED = re.compile(r"«([^»]*)»")


def strip_letter_chains(text: str) -> str:
    """Убирает «а-а-а» и «й-й-й»: голос читает их по именам букв."""

    def shorten(match: re.Match) -> str:
        # Цепочка в кавычках — это «звук, который слышно»: «на «б-б-б»».
        # Убирать её совсем нельзя: фраза рассыпается на «на «» чувствуешь
        # дрожь». Оставляем одну букву — голос назовёт её, и фраза останется
        # связной.
        inner = match.group(1).strip(" \t.,;:")
        if LETTER_CHAIN.fullmatch(inner):
            return "«" + inner[0] + "»"
        return match.group(0)

    out = QUOTED.sub(shorten, text)
    out = LETTER_CHAIN.sub("", out)
    # За цепочкой часто остаётся двоеточие или запятая: «петь: а-а-а.» ->
    # «петь.». Убираем хвосты, но не всю пунктуацию.
    out = re.sub(r"([:;,])\s*(?=[.;!?])", "", out)
    out = re.sub(r"\s+([.,;:!?])", r"\1", out)
    # Пустые кавычки после замены — мусор, который всё равно читается паузой.
    out = re.sub(r"«\s*»", "", out)
    return out


def apply_spoken_fixes(text: str) -> str:
    out = text
    for written, spoken in SPOKEN_FIXES:
        out = out.replace(written, spoken)
    return out


def add_pauses(text: str) -> str:
    for phrase in PAUSE_BEFORE:
        text = re.sub(rf"(?<!\s)(?<!\n)(?<!, )\b{re.escape(phrase)}", ", " + phrase, text)
    text = ENUM_TAIL.sub(r"\1, и ", text)
    # Двойная запятая после замены — убираем.
    text = re.sub(r",\s*,", ",", text)
    text = re.sub(r"\s+,", ",", text)
    return text


def for_speech(display_text: str, table: dict[str, str] | None = None) -> str:
    table = table if table is not None else load_stress()
    text = spell_numbers(display_text)
    text = spell_symbols(text)
    text = apply_spoken_fixes(text)
    text = strip_letter_chains(text)
    text = add_pauses(text)
    text = apply_stress(text, table)
    return re.sub(r"\s{2,}", " ", text).strip()


SAMPLES = [
    "В русском алфавите 33 буквы: десять гласных, двадцать одна согласная и два знака-помощника — твёрдый и мягкий.",
    "Ударение — это слог, который произносится громче и дольше.",
    "Ъ и Ь — буквы, но не звуки: сами не звучат, только помогают другим.",
    "Гласные тянутся голосом — их можно петь: а-а-а. Согласные «спотыкаются» о губы, зубы или язык: б-б-б.",
    "«Й» — согласная: й-й-й упирается в язык и не тянется.",
    "Проверь гласным: дуб — дуб-а, снова слышно б.",
]


def main() -> int:
    table = load_stress()
    print(f"записей в словаре озвучки: {len(table)}\n")
    for text in SAMPLES:
        print("экран:")
        print(f"  {text}")
        print("озвучка:")
        print(f"  {for_speech(text, table)}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())